-- Confiance Verify — M2: reading the MRZ ("code lines") on the rider's phone.
--   * verification.declared_document: the CNI is split into the new card (cni_biometric, which has
--     an MRZ) and the old one (cni_legacy, which has none).
--   * extracted_document_data: the MRZ lines read on the phone, encrypted inside the database with
--     pgcrypto under a key kept in Supabase Vault. Staff read them only through
--     staff_read_document_data, which audits every read before decrypting anything.
--   * check_result.capture_id: ties a check to the photo it ran on (one MRZ check per photo).
--   * RPCs for the Edge Functions (service role only): flow_record_mrz and staff_read_document_data.
--
-- Why encrypt in the database rather than in the Edge Function: the key is generated here and never
-- leaves the database (it never appears in code, chat, CI or a function's environment), and the
-- project does not log query parameters (log_statement = ddl, log_min_duration_statement = -1,
-- log_parameter_max_length_on_error = 0; checked 2026-10-13), so the plaintext lines passed to
-- flow_record_mrz stay out of the logs.

-- ---------------------------------------------------------------------------
-- Declared document: the CNI becomes two choices
-- ---------------------------------------------------------------------------
-- The old rule goes first, since it does not allow 'cni_legacy'.
alter table public.verification drop constraint verification_declared_document_check;
-- Sessions declared before M2 (test sessions only) become the old card: it has the same two sides,
-- and the flow function has no rules left for 'cni', so such a session would fail there.
update public.verification set declared_document = 'cni_legacy' where declared_document = 'cni';
alter table public.verification add constraint verification_declared_document_check
  check (declared_document in ('cni_biometric', 'cni_legacy', 'passport', 'residence_permit', 'driving_licence', 'voter_card'));

-- ---------------------------------------------------------------------------
-- Encryption key for document data
-- ---------------------------------------------------------------------------
create extension if not exists pgcrypto with schema extensions;

-- 32 random bytes generated by the database itself and kept in Vault (encrypted at rest), so nobody
-- ever handles the value. Created only once: a replacement key gets a new name
-- (document_data_key_v2) and each row records which key encrypted it (key_name).
do $$
begin
  if not exists (select 1 from vault.secrets s where s.name = 'document_data_key_v1') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'base64'),
      'document_data_key_v1',
      'Encrypts public.extracted_document_data (pgcrypto, AES-256). Generated in the database; never exported.'
    );
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Data read from the document (M2: the MRZ lines read on the phone)
-- ---------------------------------------------------------------------------
create table public.extracted_document_data (
  id               uuid primary key default gen_random_uuid(),
  verification_id  uuid not null references public.verification (id) on delete cascade,
  capture_id       uuid not null references public.capture (id) on delete cascade,
  source           text not null check (source in ('mrz_phone')),   -- mrz_phone: MRZ read on the rider's phone
  format           text not null check (format in ('TD1', 'TD3')),
  -- extensions.pgp_sym_encrypt of the lines joined with a newline, under the Vault key, with
  -- AES-256 (option cipher-algo=aes256): salted, so the same lines never give the same bytes twice.
  ciphertext       bytea not null,
  key_name         text not null,                                   -- Vault secret holding the key
  created_at       timestamptz not null default now(),
  unique (capture_id, source)                                       -- also the index for capture_id
);
create index extracted_document_data_verification_idx on public.extracted_document_data (verification_id);

-- No policy and no grant for the dashboard's roles: not even the ciphertext is visible to them.
-- Staff get the decrypted lines only from staff_read_document_data, called by the audited admin function.
alter table public.extracted_document_data enable row level security;
revoke all on public.extracted_document_data from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Check results tied to a photo
-- ---------------------------------------------------------------------------
-- Supervisors (and the assigned reviewer) read check_result directly, so its details hold outcomes
-- and counts only, never data read from the document.
alter table public.check_result
  add column capture_id uuid references public.capture (id) on delete cascade;
-- One result per check and photo. Its leading column also serves the foreign key.
create unique index check_result_capture_check_idx
  on public.check_result (capture_id, check_name) where capture_id is not null;

-- ---------------------------------------------------------------------------
-- Rider flow: record what the phone read (called by the `flow` Edge Function, service role)
-- ---------------------------------------------------------------------------
-- 'ok' when recorded, 'exists' when this photo already has its MRZ check (nothing changes),
-- 'not_found' when the capture is not a live capture of this verification. The encrypted lines (when
-- some were read), the check result and the audit entry are written together or not at all.
-- SECURITY DEFINER: it reads the key from Vault, which the API roles cannot read.
create function public.flow_record_mrz(
  p_verification uuid,
  p_capture uuid,
  p_lines text,
  p_format text,
  p_outcome public.check_outcome,
  p_details jsonb
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  doc_key text;
  -- AES-256 rather than pgcrypto's default AES-128. A named constant also keeps the quoted option
  -- away from the key's name, which the CI secret scan (gitleaks) would read as a leaked key.
  pgp_options constant text := 'cipher-algo=aes256';
begin
  -- The flow function validates the lines strictly and recomputes every check digit before calling;
  -- this only refuses data that is not an MRZ of the given format. The message never repeats the value.
  if p_lines is not null and not coalesce(
       (p_format = 'TD1' and p_lines ~ '^[A-Z0-9<]{30}\n[A-Z0-9<]{30}\n[A-Z0-9<]{30}$')
    or (p_format = 'TD3' and p_lines ~ '^[A-Z0-9<]{44}\n[A-Z0-9<]{44}$'), false) then
    raise exception 'flow_record_mrz: lines do not match the format' using errcode = 'invalid_parameter_value';
  end if;

  -- The row lock queues a retried report behind the first one, which then finds the result written.
  perform 1 from public.capture c
   where c.id = p_capture and c.verification_id = p_verification and c.deleted_at is null
   for update;
  if not found then
    return 'not_found';
  end if;

  -- 'mrz' is MRZ_CHECK_NAME in contract.ts; the dashboard looks the check up by it.
  if exists (select 1 from public.check_result cr where cr.capture_id = p_capture and cr.check_name = 'mrz') then
    return 'exists';
  end if;

  if p_lines is not null then
    select ds.decrypted_secret into doc_key from vault.decrypted_secrets ds where ds.name = 'document_data_key_v1';
    if doc_key is null then
      raise exception 'flow_record_mrz: the key document_data_key_v1 is missing from Vault';
    end if;
    insert into public.extracted_document_data (verification_id, capture_id, source, format, ciphertext, key_name)
    values (p_verification, p_capture, 'mrz_phone', p_format,
            extensions.pgp_sym_encrypt(p_lines, doc_key, pgp_options), 'document_data_key_v1');
  end if;

  insert into public.check_result (verification_id, capture_id, check_name, check_version, outcome, details)
  values (p_verification, p_capture, 'mrz', p_details ->> 'parserVersion', p_outcome, p_details);

  -- The outcome only: the lines, and anything read from them, never go into the audit log.
  insert into public.audit_event (actor_type, actor_id, action, target_type, target_id, details)
  values ('rider', p_verification::text, 'mrz.record', 'verification', p_verification::text,
          jsonb_build_object('captureId', p_capture, 'outcome', p_outcome, 'result', p_details ->> 'result'));
  return 'ok';
end;
$$;

-- ---------------------------------------------------------------------------
-- Staff: read the decrypted data of a case (called by the `admin` Edge Function, service role)
-- ---------------------------------------------------------------------------
-- Writes the audit entry first, then returns the decrypted lines (latest first), in the same
-- transaction: if the entry cannot be written, nothing is decrypted or returned. The entry counts
-- exactly the rows returned. A read of a case with no data is audited too. The access rule of the admin function is checked again here, so a
-- mistake there cannot reveal data: active staff whose role matches p_role, reviewer or supervisor
-- (never admin), and a reviewer only while the case is assigned to them.
create function public.staff_read_document_data(p_verification uuid, p_actor uuid, p_role text)
returns table (capture_id uuid, source text, format text, lines text, recorded_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  items public.extracted_document_data[];
begin
  if p_role is null or p_role not in ('reviewer', 'supervisor')
     or not exists (
       select 1 from public.staff_profile sp
       where sp.user_id = p_actor and sp.active and sp.role::text = p_role)
     or (p_role = 'reviewer' and not exists (
       select 1 from public.review_task rt
       where rt.verification_id = p_verification and rt.assigned_to = p_actor and rt.status = 'assigned')) then
    raise exception 'staff_read_document_data: not allowed' using errcode = 'insufficient_privilege';
  end if;

  -- The rows are read once, and the key check, the audit count and the decryption all use that one
  -- set. Each statement of this function sees the rows committed before it starts, so reading the
  -- table again could return a row that a rider's report (flow_record_mrz) committed after the
  -- count, and the audit entry would understate what was revealed.
  select coalesce(array_agg(edd), '{}') into items
    from public.extracted_document_data edd where edd.verification_id = p_verification;

  -- Fail loudly rather than return empty lines when a row's key is gone.
  if exists (
    select 1 from unnest(items) i
    where not exists (select 1 from vault.decrypted_secrets ds where ds.name = i.key_name and ds.decrypted_secret is not null)
  ) then
    raise exception 'staff_read_document_data: a document data key is missing from Vault';
  end if;

  insert into public.audit_event (actor_type, actor_id, action, target_type, target_id, details)
  values ('staff', p_actor::text, 'document_data.view', 'verification', p_verification::text,
          jsonb_build_object('role', p_role, 'items', cardinality(items)));

  return query
    select i.capture_id, i.source, i.format,
           extensions.pgp_sym_decrypt(i.ciphertext, ds.decrypted_secret),
           i.created_at
    from unnest(items) i
    join vault.decrypted_secrets ds on ds.name = i.key_name
    order by i.created_at desc, i.id desc;
end;
$$;

revoke execute on function public.flow_record_mrz(uuid, uuid, text, text, public.check_outcome, jsonb)
  from public, anon, authenticated;
revoke execute on function public.staff_read_document_data(uuid, uuid, text) from public, anon, authenticated;
grant execute on function public.flow_record_mrz(uuid, uuid, text, text, public.check_outcome, jsonb) to service_role;
grant execute on function public.staff_read_document_data(uuid, uuid, text) to service_role;
