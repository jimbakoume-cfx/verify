"""Writes tests/fixtures/quality_reference.json: the rider app's TypeScript quality measurements on
the images of tests/quality_inputs.py, for the parity test of verify_worker/quality.py.

Run again only when packages/capture's maths or the specimens change (needs Node and the repo's
node_modules):    cd worker && uv run python tests/tools/make_quality_reference.py
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORKER = HERE.parent.parent
REPO = WORKER.parent
sys.path.insert(0, str(WORKER))
sys.path.insert(0, str(HERE.parent))

from quality_inputs import CASES, analysis_gray  # noqa: E402


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = Path(tmp)
        listing = []
        hashes = {}
        for name, file, change in CASES:
            gray = analysis_gray(file, change)
            h, w = gray.shape
            pgm = tmpdir / f"{name}.pgm"
            pgm.write_bytes(f"P5\n{w} {h}\n255\n".encode("ascii") + gray.tobytes())
            listing.append({"name": name, "pgm": str(pgm)})
            hashes[name] = hashlib.sha256(gray.tobytes()).hexdigest()
        (tmpdir / "list.json").write_text(json.dumps(listing))
        bundle = tmpdir / "quality_reference.mjs"
        subprocess.run(
            ["npx", "rolldown", str(HERE / "quality_reference.ts"), "--file", str(bundle), "--format", "esm", "--platform", "node"],
            cwd=REPO,
            check=True,
            capture_output=True,
        )
        result = subprocess.run(["node", str(bundle), str(tmpdir / "list.json")], check=True, capture_output=True, text=True)
    cases = json.loads(result.stdout)
    for case in cases:
        case["graySha256"] = hashes[case["name"]]
    out = {
        "about": "Quality measurements by packages/capture (TypeScript) on the gray images of tests/quality_inputs.py. "
                 "Generated by tests/tools/make_quality_reference.py; do not edit by hand.",
        "cases": cases,
    }
    target = WORKER / "tests" / "fixtures" / "quality_reference.json"
    target.write_text(json.dumps(out, indent=1) + "\n")
    print(f"{len(cases)} cases -> {target}")


if __name__ == "__main__":
    main()
